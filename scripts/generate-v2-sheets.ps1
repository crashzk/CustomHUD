<#
.SYNOPSIS
    Generates the v2 layouts' copies of the shared sheets, in CS2's store palette:
    styles/custom_game/customhud/v2/<sheet>.vcss.

.DESCRIPTION
    The v2 layouts draw the same anatomy as the first designs, so they reuse those sheets'
    rules; only the palette differs. Panorama substitutes a @define as text, and a sheet is
    most likely parsed once per file, so one sheet cannot serve both designs under different
    token values. Each sheet below gets a copy instead, with the first design's palette
    tokens renamed to the store tokens in customhud_tokens.vcss; every other token (gold,
    rarity, teams ...) is shared as it is.

    Edit the source sheets, never the copies. Rerun after changing a source sheet or the
    map below, then rerun watch-panorama.ps1. A name the copies use that customhud_tokens.vcss
    does not define is reported and fails the run.
#>
[CmdletBinding()]
param([string] $StylesDir = $null)

$ErrorActionPreference = 'Stop'
if (-not $StylesDir) { $StylesDir = Join-Path $PSScriptRoot '..\resources\panorama\styles\custom_game\customhud' }
$StylesDir = [IO.Path]::GetFullPath($StylesDir)
$OutDir = Join-Path $StylesDir 'v2'

$Sheets = 'menu', 'menu_mouse', 'locker', 'locker_shop', 'locker_maps', 'locker_ranks', 'locker_vip',
          'locker_admins', 'locker_mix', 'list', 'hud_text', 'hud_alert'

# First design -> store look. The accent is CS2's selectedNavColor, surfaces its navy panel and
# white hairlines, tiles glass over shade, and secondary text its neutral greys.
$Map = [ordered]@{
    chudAccentBase    = 'chudNavBase'
    chudAccentStrong  = 'chudNavStrong'
    chudAccentHalf    = 'chudNavHalf'
    chudAccentDim     = 'chudNavDim'
    chudAccentSoft    = 'chudNavSoft'
    chudAccentWash    = 'chudNavWash'
    chudAccentFade    = 'chudNavFade'
    chudSurfaceBase   = 'chudStoreDeep'
    chudSurfaceRaised = 'chudStoreRaised'
    chudSurfaceDeep   = 'chudStoreDeep'
    chudSurfaceEdge   = 'chudStoreEdge'
    chudSurfaceFade   = 'chudStoreFade'
    chudSurfaceRow    = 'chudStoreRow'
    chudSurfaceHover  = 'chudStoreHover'
    chudTileBase      = 'chudStoreTileBase'
    chudTileDeep      = 'chudStoreTileDeep'
    chudTileHover     = 'chudStoreTileHover'
    chudTileFade      = 'chudStoreTileFade'
    chudTextMuted     = 'chudStoreText'
    chudTextFaint     = 'chudStoreFaint'
}

$tokens = [regex]::Matches([IO.File]::ReadAllText((Join-Path $StylesDir 'customhud_tokens.vcss')), '@define\s+(\w+)\s*:') |
    ForEach-Object { $_.Groups[1].Value }
$defined = [Collections.Generic.HashSet[string]]::new([string[]] $tokens)
foreach ($target in $Map.Values) { if (-not $defined.Contains($target)) { throw "customhud_tokens.vcss does not define $target." } }

$pattern = [regex] ('\b(' + (($Map.Keys | Sort-Object Length -Descending) -join '|') + ')\b')
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$missing = @()
foreach ($sheet in $Sheets) {
    $source = Join-Path $StylesDir "$sheet.vcss"
    $text = [IO.File]::ReadAllText($source).Replace("`r`n", "`n")
    $copy = $pattern.Replace($text, { param($m) $Map[$m.Value] })
    $header = "/* Generated by scripts/generate-v2-sheets.ps1 from $sheet.vcss in the store palette. Do not edit. */`n`n"
    [IO.File]::WriteAllText((Join-Path $OutDir "$sheet.vcss"), $header + $copy, (New-Object System.Text.UTF8Encoding $false))
    $missing += [regex]::Matches($copy, '\bchud[A-Z]\w*') | ForEach-Object { $_.Value } |
        Where-Object { -not $defined.Contains($_) } | ForEach-Object { "$sheet.vcss: $_" }
    Write-Host ("v2/{0}.vcss <- {1}.vcss" -f $sheet, $sheet)
}
if ($missing) {
    $missing | Sort-Object -Unique | ForEach-Object { Write-Host "missing token  $_" -ForegroundColor Red }
    exit 1
}
